"""Leakage-safe telemetry preprocessing and temporal feature engineering module.

Provides scaling transformations and backward-looking temporal feature engineering
for satellite telemetry channels. All scaling parameters are learned strictly from
training partitions to prevent future-to-past data leakage.
"""

from typing import Dict, List, Optional
import numpy as np
import pandas as pd


class NotFittedError(ValueError):
    """Raised when transform is called before fit on a TelemetryPreprocessor."""
    pass


class TelemetryPreprocessor:
    """Telemetry data preprocessor guaranteeing zero temporal leakage.

    Learns centering and scaling statistics strictly from training observations,
    then transforms subsequent test partitions using the identical parameters.

    Temporal Feature Engineering:
    - Backward-looking rolling statistics (mean, std) use past observations only.
    - Differencing features (rate-of-change) use backward first-differences: x_t - x_{t-1}.
    - Boundary behavior: at t=0, rolling windows use min_periods=1 (past data only)
      and differencing assigns 0.0 to prevent row-dropping or lookahead bias.

    Attributes:
        scaler_type: Normalization scheme ("standard", "minmax", "robust", or "none").
        feature_cols: Explicit list of telemetry channels to process.
        timestamp_col: Name of timestamp column to preserve.
        add_rolling_stats: Whether to compute backward rolling mean and standard deviation.
        rolling_window: Size of past window in timesteps (e.g. 5 minutes).
        add_differencing: Whether to compute backward first-order rate of change.
        fitted_: Boolean indicating whether preprocessor has learned parameters.
        feature_names_out_: List of output feature column names generated by transform.
    """

    def __init__(
        self,
        scaler_type: str = "standard",
        feature_cols: Optional[List[str]] = None,
        timestamp_col: str = "timestamp",
        add_rolling_stats: bool = False,
        rolling_window: int = 5,
        add_differencing: bool = False,
    ):
        valid_scalers = {"standard", "minmax", "robust", "none"}
        if scaler_type not in valid_scalers:
            raise ValueError(
                f"Unsupported scaler_type '{scaler_type}'. Choose from {valid_scalers}."
            )
        if rolling_window < 1:
            raise ValueError(f"rolling_window must be at least 1, got {rolling_window}.")

        self.scaler_type = scaler_type
        self.feature_cols = feature_cols
        self.timestamp_col = timestamp_col
        self.add_rolling_stats = add_rolling_stats
        self.rolling_window = rolling_window
        self.add_differencing = add_differencing

        self.fitted_: bool = False
        self.learned_params_: Dict[str, Dict[str, float]] = {}
        self.resolved_feature_cols_: List[str] = []
        self.feature_names_out_: List[str] = []

    def fit(self, X: pd.DataFrame) -> "TelemetryPreprocessor":
        """Fits normalization parameters strictly on training observations.

        Args:
            X: Training DataFrame containing telemetry features.

        Returns:
            self: The fitted preprocessor instance.

        Raises:
            ValueError: If input DataFrame is empty or missing required columns.
        """
        if not isinstance(X, pd.DataFrame):
            raise TypeError(f"Input X must be a pandas DataFrame, got {type(X).__name__}.")
        if X.empty:
            raise ValueError("Cannot fit preprocessor on an empty DataFrame.")

        # Resolve telemetry feature columns
        if self.feature_cols is not None:
            missing = [c for c in self.feature_cols if c not in X.columns]
            if missing:
                raise ValueError(f"Required feature column(s) missing from training data: {missing}")
            self.resolved_feature_cols_ = list(self.feature_cols)
        else:
            # Auto-infer all numeric columns, excluding timestamp and labels
            excluded = {self.timestamp_col, "is_anomaly", "anomaly_type", "label", "ground_truth"}
            numeric_cols = [
                c for c in X.columns
                if c not in excluded and pd.api.types.is_numeric_dtype(X[c])
            ]
            if not numeric_cols:
                raise ValueError("No numeric telemetry channels found in training data.")
            self.resolved_feature_cols_ = numeric_cols

        # Learn scaling statistics for each channel
        self.learned_params_ = {}
        for col in self.resolved_feature_cols_:
            series = X[col].astype(float)
            if self.scaler_type == "standard":
                mean_val = float(series.mean())
                std_val = float(series.std(ddof=0))
                # Protect against zero division for constant channels
                scale_val = std_val if std_val > 1e-8 else 1.0
                self.learned_params_[col] = {"center": mean_val, "scale": scale_val}
            elif self.scaler_type == "minmax":
                min_val = float(series.min())
                max_val = float(series.max())
                range_val = (max_val - min_val) if (max_val - min_val) > 1e-8 else 1.0
                self.learned_params_[col] = {"center": min_val, "scale": range_val}
            elif self.scaler_type == "robust":
                q25 = float(series.quantile(0.25))
                median = float(series.median())
                q75 = float(series.quantile(0.75))
                iqr = (q75 - q25) if (q75 - q25) > 1e-8 else 1.0
                self.learned_params_[col] = {"center": median, "scale": iqr}
            elif self.scaler_type == "none":
                self.learned_params_[col] = {"center": 0.0, "scale": 1.0}

        # Determine output feature names
        out_names = list(self.resolved_feature_cols_)
        if self.add_rolling_stats:
            for col in self.resolved_feature_cols_:
                out_names.extend([f"{col}_roll_mean_{self.rolling_window}", f"{col}_roll_std_{self.rolling_window}"])
        if self.add_differencing:
            for col in self.resolved_feature_cols_:
                out_names.append(f"{col}_diff_1")
        self.feature_names_out_ = out_names

        self.fitted_ = True
        return self

    def transform(self, X: pd.DataFrame, include_timestamp: bool = True) -> pd.DataFrame:
        """Transforms observations using strictly pre-fitted training statistics.

        Boundary Guarantee:
        - Never uses future observations for earlier timesteps.
        - Preserves all rows: len(output) == len(X).
        - Preserves original index and timestamps for exact anomaly alignment.

        Args:
            X: Telemetry DataFrame to transform (train or test).
            include_timestamp: If True, preserves the timestamp column in output. Defaults to True.

        Returns:
            pd.DataFrame: Transformed telemetry features with identical row indexing.

        Raises:
            NotFittedError: If `transform` is called before `fit`.
            ValueError: If `X` is missing any fitted feature channels.
        """
        if not self.fitted_:
            raise NotFittedError("TelemetryPreprocessor must be fitted on training data before calling transform.")
        if not isinstance(X, pd.DataFrame):
            raise TypeError(f"Input X must be a pandas DataFrame, got {type(X).__name__}.")
        if X.empty:
            raise ValueError("Cannot transform an empty DataFrame.")

        missing = [c for c in self.resolved_feature_cols_ if c not in X.columns]
        if missing:
            raise ValueError(f"Input DataFrame is missing fitted feature columns: {missing}")

        result_df = pd.DataFrame(index=X.index)

        # Preserve timestamp column if present and requested
        if include_timestamp and self.timestamp_col in X.columns:
            result_df[self.timestamp_col] = X[self.timestamp_col].values

        # 1. Scale base features using learned training parameters
        for col in self.resolved_feature_cols_:
            params = self.learned_params_[col]
            series = X[col].astype(float)
            scaled = (series - params["center"]) / params["scale"]
            result_df[col] = scaled.values

        # 2. Backward-looking rolling features
        if self.add_rolling_stats:
            for col in self.resolved_feature_cols_:
                scaled_series = pd.Series(result_df[col].values, index=X.index)
                # min_periods=1 ensures no lookahead, uses past observations only, no NaNs dropped
                roll_mean = scaled_series.rolling(window=self.rolling_window, min_periods=1).mean()
                roll_std = scaled_series.rolling(window=self.rolling_window, min_periods=1).std().fillna(0.0)
                result_df[f"{col}_roll_mean_{self.rolling_window}"] = roll_mean.values
                result_df[f"{col}_roll_std_{self.rolling_window}"] = roll_std.values

        # 3. Backward differencing features (x_t - x_{t-1})
        if self.add_differencing:
            for col in self.resolved_feature_cols_:
                scaled_series = pd.Series(result_df[col].values, index=X.index)
                diff_series = scaled_series.diff(periods=1).fillna(0.0)
                result_df[f"{col}_diff_1"] = diff_series.values

        return result_df

    def fit_transform(self, X: pd.DataFrame, include_timestamp: bool = True) -> pd.DataFrame:
        """Fits preprocessor on X and returns transformed DataFrame.

        Args:
            X: Training DataFrame.
            include_timestamp: If True, preserves timestamp column in output.

        Returns:
            pd.DataFrame: Transformed training features.
        """
        return self.fit(X).transform(X, include_timestamp=include_timestamp)

    def get_feature_names_out(self) -> List[str]:
        """Returns the list of transformed feature channel column names."""
        if not self.fitted_:
            raise NotFittedError("Preprocessor must be fitted before retrieving feature names.")
        return list(self.feature_names_out_)
